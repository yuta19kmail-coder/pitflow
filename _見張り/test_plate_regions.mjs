/* 地域名ではないもの（市の名前・昔の書き方）＝候補に出してはいけない */
const NG_WORDS = { 'さいたま':'大宮', '栃木':'とちぎ', '飯田':'南信州', '周南':'山口' };

const REF_ALL = [];
Object.keys(REF).forEach(k => REF[k].forEach(x => { if (REF_ALL.indexOf(x) < 0) REF_ALL.push(x); }));

const src = fs.readFileSync(path.join(process.cwd(), 'js', 'card-detail.js'), 'utf8');
const m = src.match(/const PLATE_REGIONS = \[([\s\S]*?)\n\];/);

console.log('\n── 🚗 ナンバーの地名の候補 ──');
ok('候補の表がある（PLATE_REGIONS）', !!m);
const cur = m ? (m[1].match(/'([^']+)'/g) || []).map(s => s.slice(1, -1)) : [];

const miss  = REF_ALL.filter(x => cur.indexOf(x) < 0);
const extra = cur.filter(x => REF_ALL.indexOf(x) < 0);
const dup   = cur.filter((x, i) => cur.indexOf(x) !== i);

ok('🔴 国交省の表にある地名が全部そろっている（' + REF_ALL.length + '件）', miss.length === 0, miss);
ok('🔴 表に無い地名が混ざっていない', extra.length === 0, extra);
ok('同じ地名が2回入っていない', dup.length === 0, dup);
ok('件数が合う', cur.length === REF_ALL.length, { app: cur.length, ref: REF_ALL.length });

console.log('\n── 📍 名指しで見る（今回の報告と、消した4つ） ──');
ok('🔴 市原がある（ゆうた報告 2026-08-28）', cur.indexOf('市原') >= 0);
['郡山','白河'].forEach(x => ok(x + 'がある（福島のご当地）', cur.indexOf(x) >= 0));
Object.keys(NG_WORDS).forEach(x => {
  ok('🔴 ' + x + ' を出さない（正しくは「' + NG_WORDS[x] + '」）', cur.indexOf(x) < 0);
});

console.log('\n── 🗾 都道府県ごとに1つずつ ──');
Object.keys(REF).forEach(k => {
  const bad = REF[k].filter(x => cur.indexOf(x) < 0);
  ok(k + '（' + REF[k].length + '件）', bad.length === 0, bad);
});

console.log('\n===== ' + OK + ' OK / ' + NG + ' NG =====');
process.exit(NG ? 1 : 0);
